#!/usr/bin/env python3
"""Compile the presenter's GLSL shaders into a C++ header of SPIR-V words.

The header is committed, so native builds need no shader compiler. Run this
after changing native/android/core/shaders/; --check fails when the committed
header is out of date. Uses the NDK's glslc.
"""

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ndk  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / 'native/android/core/shaders'
HEADER = ROOT / 'native/android/core/boxdroid-present-shaders.h'
# Source file -> C++ array name.
OUTPUTS = {'present.vert': 'kPresentVertexShader', 'present.frag': 'kPresentFragmentShader',
           'sgsr1.frag': 'kSgsrFragmentShader'}


def glslc():
    tool = ndk.get_ndk_path() / 'shader-tools' / ndk.get_host_tag() / 'glslc'
    if not tool.exists():
        raise ndk.NdkNotFoundError(f'glslc not found at {tool}')
    return tool


def compile_spirv(compiler, source):
    with tempfile.TemporaryDirectory() as temporary:
        output = Path(temporary) / 'shader.spv'
        subprocess.run([str(compiler), '-O', '--target-env=vulkan1.0', '-o', str(output), str(source)],
                       check=True)
        data = output.read_bytes()
    if len(data) % 4:
        raise RuntimeError(f'{source.name}: SPIR-V size {len(data)} is not a multiple of 4')
    return [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]


def render(arrays):
    lines = ['// Generated by scripts/compile-shaders.py from native/android/core/shaders/.',
             '// Do not edit; change the GLSL sources and run the script again.',
             '#pragma once', '', '#include <cstdint>', '']
    for name, words in arrays.items():
        lines.append(f'static const uint32_t {name}[] = {{')
        for i in range(0, len(words), 8):
            lines.append('    ' + ', '.join(f'0x{word:08x}' for word in words[i:i + 8]) + ',')
        lines.extend(['};', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='fail if the header is out of date')
    args = parser.parse_args()
    compiler = glslc()
    text = render({name: compile_spirv(compiler, SHADERS / source) for source, name in OUTPUTS.items()})
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            sys.exit(f'{HEADER.relative_to(ROOT)} is out of date: run scripts/compile-shaders.py')
        return
    HEADER.write_text(text)
    print(f'wrote {HEADER.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
